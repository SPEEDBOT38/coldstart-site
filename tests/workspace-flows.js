(async()=>{
  const report=[],wait=(n=80)=>new Promise(r=>setTimeout(r,n)),key='coldstart-workspace-v1';
  const s=()=>JSON.parse(localStorage.getItem(key));
  const check=(name,value)=>report.push({name,pass:!!value});
  const go=async r=>{location.hash='/'+r;await wait();};
  const click=async sel=>{const e=document.querySelector(sel);if(!e)throw new Error('Missing control: '+sel);e.click();await wait();};
  const fill=(sel,value)=>{const e=document.querySelector(sel);if(!e)throw new Error('Missing input: '+sel);e.value=value;e.dispatchEvent(new Event('input',{bubbles:true}));};
  const change=async(sel,value)=>{const e=document.querySelector(sel);e.value=value;e.dispatchEvent(new Event('change',{bubbles:true}));await wait();};
  const submit=async sel=>{document.querySelector(sel).requestSubmit();await wait();};
  try {
    await go('research');
    await click('[data-research="signals"]');
    await click('[data-signal="s1"]');
    const beforeSaved=s().saved.includes('s1');await click('[data-action="save-signal"]');
    check('evidence bookmark toggles and persists',s().saved.includes('s1')!==beforeSaved);
    await click('[data-action="signal-draft"]');
    await change('#new-draft-form [name="platform"]','x');
    fill('#new-draft-form [name="title"]','Browser QA / soil check');
    fill('#new-draft-form [name="body"]','Check the soil before adding more water. A simple routine beats a fixed schedule.');
    await submit('#new-draft-form');
    let id=s().ui.selected;
    check('evidence creates destination draft',s().posts.find(p=>p.id===id)?.sourceId==='s1');
    check('draft opens studio',location.hash==='#/studio');
    await click('[data-action="approve"][data-id="'+id+'"]');
    check('per-post approval persists',s().posts.find(p=>p.id===id).approved);
    await click('[data-action="open-calendar"][data-id="'+id+'"]');
    await submit('#schedule-form');
    check('approved post schedules', ['scheduled','held'].includes(s().posts.find(p=>p.id===id).status));
    await click('[data-action="pause-queue"]');
    check('pause holds scheduled content',s().paused && s().posts.find(p=>p.id===id).status==='held');
    await click('[data-action="pause-queue"]');
    check('resume restores eligible content',!s().paused && s().posts.find(p=>p.id===id).status==='scheduled');
    await change('#timezone','UTC');
    check('timezone setting persists',s().ui.zone==='UTC');
    await click('[data-action="edit-post"][data-id="'+id+'"]');
    fill('#draft-body','Edited after approval. A fresh review is required.');await submit('#draft-form');
    let p=s().posts.find(p=>p.id===id);
    check('editing invalidates approval',!p.approved);
    check('editing clears scheduled timestamp',!p.scheduledAt);
    await click('[data-action="open-calendar"][data-id="'+id+'"]');await submit('#schedule-form');
    check('cannot schedule unapproved edited copy',!s().posts.find(p=>p.id===id).scheduledAt);
    await go('studio');
    await click('[name="policy"][value="batch"]');
    check('batch policy saved from ribbon',s().campaigns.find(c=>c.id===s().ui.campaign).policy==='batch');
    await click('[data-action="review-batch"]');check('batch review dialog displays content',document.querySelector('#dialog .batch-row'));
    await click('[data-action="confirm-batch"]');
    check('batch applies approval',s().posts.find(p=>p.id===id).approved);
    await click('[name="policy"][value="auto"]');
    check('auto policy saved from ribbon',s().campaigns.find(c=>c.id===s().ui.campaign).policy==='auto');
    await click('[data-action="auto-rules"]');
    check('automatic rule controls available',document.querySelectorAll('#policy-rules-form [name="allowed"]').length===5);
    await click('[data-action="close-dialog"]');
    await click('[data-action="apply-auto"]');check('automatic rule evaluation responds',document.querySelector('#toast').textContent.length>0);
    await go('connections');
    if(s().connections.x)await click('[data-action="connection"][data-platform="x"]');
    check('destination disconnects',!s().connections.x);
    await click('[data-action="connection"][data-platform="x"]');
    check('connecting explicitly labelled simulation',/No authorization request/.test(document.querySelector('#dialog').innerText));
    await click('[data-action="confirm-connect"]');check('destination connects in local state',s().connections.x);
    await go('tracking');for(let i=0;i<40&&!document.querySelector('#step-connect');i++)await wait(100);
    check('tracking shows the Meta connect step from the live API',!!document.querySelector('#step-connect'));
    const metaOn=!!document.querySelector('#step-connect.done');
    check('Meta connect offers OAuth and the token path',metaOn||(!!document.querySelector('a[href="/api/plugins/meta/connect"]')&&!!document.querySelector('[data-action="meta-token-dialog"]')));
    if(!metaOn){await click('[data-action="meta-token-dialog"]');check('token form never echoes the token',document.querySelector('#meta-token-form [name="access_token"]').type==='password');await click('[data-action="close-dialog"]');}
    check('four setup steps rendered',['#step-connect','#step-dataset','#step-install','#step-verify'].every(x=>document.querySelector(x)));
    await go('ads');const paused=s().paused;await click('[data-action="pause-ads"]');
    check('ad pause independent of organic queue',s().paused===paused && s().adsPaused);
    await click('[data-action="new-ad"]');fill('#ad-form [name="title"]','Browser QA / ad draft');await submit('#ad-form');
    check('paid draft created locally',s().ads.some(a=>a.title==='Browser QA / ad draft'&&a.status==='draft'));
    await click('[data-action="search"]');fill('#global-search','soil check');
    check('global search finds content',!!document.querySelector('[data-search-post]'));
    await click('[data-action="close-dialog"]');
    await go('research');await click('[data-research="signals"]');
    check('live scan form offers Reddit, X and Instagram',document.querySelectorAll('#live-scan-form [name="src"]').length===3);
    check('live scan needs a question',document.querySelector('#live-scan-form [name="query"]').required);
    await click('[data-research="competitors"]');
    check('competitors can pull the live Meta Ad Library',!!document.querySelector('#live-ads-form'));
  } catch(e) {report.push({name:'Flow exception: '+e.message,pass:false});}
  return {checks:report.length,failures:report.filter(r=>!r.pass),details:report};
})()
